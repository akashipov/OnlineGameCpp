#pragma once
// Измеритель "неровности" потока пакетов, которые отправляются равномерно (раз в тик).
//
// Пакет №k отправлен в момент k/60. Если бы сеть была идеальной, он пришёл бы в k/60 + const.
// sample = k - (время прихода × 60) — "какой номер должен быть сейчас", если пакет пришёл без задержки.
//  offset — среднее sample (средняя задержка сети),
//  jitter — среднее отклонение от него в тиках (насколько пакеты опаздывают/спешат).
//
// Используется дважды:
//  - клиентом, для снимков от сервера (render_clock.h): сколько запаса держать при отрисовке соперника;
//  - сервером, для вводов игрока: сколько вводов держать в буфере, чтобы двигать игрока ровно.

#include <cmath>

struct JitterMeter {
    double offset = 0;        // (номер пакета) - (время прихода × частота), сглаженное
    double jitterTicks = 1;   // насколько неровно приходят пакеты, в тиках
    double decay = 0.005;     // как быстро jitter уменьшается, когда сеть успокоилась

    void add(double sample) {
        if (!init_) {
            offset = sample;
            init_ = true;
            return;
        }
        double dev = sample - offset;
        offset += dev * 0.05;   // средняя задержка, плавно

        // jitter растёт быстро (скачок сети), а уменьшается медленно (decay),
        // чтобы после одного скачка не сократить запас и не словить следующий
        double a = std::fabs(dev) > jitterTicks ? 0.1 : decay;
        jitterTicks += (std::fabs(dev) - jitterTicks) * a;
    }

    bool ready() const { return init_; }

private:
    bool init_ = false;
};
